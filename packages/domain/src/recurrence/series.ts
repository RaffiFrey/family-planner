import { addFloating, floatingToInstant, instantToFloating } from '../time/time.js';
import { RRule, type RRuleOptions } from './rrule-interop.js';

/**
 * A recurring (or single) calendar entry.
 *
 * Timed entries: `start`/`end` are absolute instants and the rule repeats in `timeZone` wall time,
 * so a 09:00 event stays at 09:00 across DST changes.
 * All-day entries: `start`/`end` are floating UTC midnights (see `localDateToFloating`), `end` exclusive.
 */
export interface SeriesDefinition {
  start: Date;
  end: Date;
  timeZone: string;
  allDay: boolean;
  /** RFC 5545 RRULE body without DTSTART, e.g. `FREQ=WEEKLY;BYDAY=MO,WE`. */
  rrule?: string | null | undefined;
}

export interface OccurrenceException {
  /** Start of the occurrence as generated by the rule (identifies the occurrence). */
  originalStart: Date;
  cancelled?: boolean;
  start?: Date;
  end?: Date;
}

export interface Occurrence {
  originalStart: Date;
  start: Date;
  end: Date;
  modified: boolean;
}

export interface DateRange {
  from: Date;
  to: Date;
}

export class RecurrenceError extends Error {
  override name = 'RecurrenceError';
}

const ALLOWED_PARTS = new Set([
  'FREQ',
  'INTERVAL',
  'COUNT',
  'UNTIL',
  'BYDAY',
  'BYMONTHDAY',
  'BYMONTH',
  'BYSETPOS',
  'WKST',
]);
const ALLOWED_FREQ = new Set(['DAILY', 'WEEKLY', 'MONTHLY', 'YEARLY']);

/** Validates the supported RRULE subset; returns normalized rrule options. */
export function parseRecurrenceRule(rrule: string): Partial<RRuleOptions> {
  const body = rrule.trim().replace(/^RRULE:/i, '');
  if (body === '') throw new RecurrenceError('Empty recurrence rule');
  const parts = body.split(';').filter(Boolean);
  const seen = new Set<string>();
  for (const part of parts) {
    const [key, value] = part.split('=');
    if (!key || value === undefined || value === '')
      throw new RecurrenceError(`Malformed rule part "${part}"`);
    const upper = key.toUpperCase();
    if (!ALLOWED_PARTS.has(upper)) throw new RecurrenceError(`Unsupported rule part "${upper}"`);
    if (seen.has(upper)) throw new RecurrenceError(`Duplicate rule part "${upper}"`);
    seen.add(upper);
    if (upper === 'FREQ' && !ALLOWED_FREQ.has(value.toUpperCase())) {
      throw new RecurrenceError(`Unsupported frequency "${value}"`);
    }
  }
  if (!seen.has('FREQ')) throw new RecurrenceError('Rule needs FREQ');
  if (seen.has('COUNT') && seen.has('UNTIL'))
    throw new RecurrenceError('COUNT and UNTIL are exclusive');
  try {
    const options = RRule.parseString(body.toUpperCase());
    if (
      options.interval !== undefined &&
      (options.interval < 1 || !Number.isInteger(options.interval))
    ) {
      throw new RecurrenceError('INTERVAL must be a positive integer');
    }
    if (options.count !== undefined && options.count !== null && options.count < 1) {
      throw new RecurrenceError('COUNT must be positive');
    }
    return options;
  } catch (e) {
    if (e instanceof RecurrenceError) throw e;
    throw new RecurrenceError(`Invalid rule "${rrule}": ${(e as Error).message}`);
  }
}

function floatingStart(series: SeriesDefinition): Date {
  return series.allDay ? series.start : instantToFloating(series.start, series.timeZone);
}

function toInstant(series: SeriesDefinition, floating: Date): Date {
  return series.allDay ? floating : floatingToInstant(floating, series.timeZone);
}

function buildRule(series: SeriesDefinition): RRule | null {
  if (!series.rrule) return null;
  return new RRule({ ...parseRecurrenceRule(series.rrule), dtstart: floatingStart(series) });
}

function durationMs(series: SeriesDefinition): number {
  const d = series.end.getTime() - series.start.getTime();
  if (d < 0) throw new RecurrenceError('end must not be before start');
  return d;
}

function overlaps(start: Date, end: Date, range: DateRange): boolean {
  // Zero-length entries (reminders, deadlines) count when they start inside the range.
  if (start.getTime() === end.getTime()) return start >= range.from && start < range.to;
  return start < range.to && end > range.from;
}

/** Expands a series into concrete occurrences overlapping `range`, applying exceptions. */
export function expandOccurrences(
  series: SeriesDefinition,
  range: DateRange,
  exceptions: readonly OccurrenceException[] = [],
  limit = 2000,
): Occurrence[] {
  const duration = durationMs(series);
  const byOriginal = new Map(exceptions.map((e) => [e.originalStart.getTime(), e]));
  const rule = buildRule(series);

  const originals: Date[] = [];
  if (!rule) {
    originals.push(series.start);
  } else {
    // Pad by a day plus the duration so DST offsets and long events can't drop occurrences.
    const tz = series.timeZone;
    const fromF = addFloating(
      series.allDay
        ? new Date(range.from.getTime() - duration)
        : instantToFloating(new Date(range.from.getTime() - duration), tz),
      -1,
      'day',
    );
    const toF = addFloating(series.allDay ? range.to : instantToFloating(range.to, tz), 1, 'day');
    for (const f of rule.between(fromF, toF, true)) {
      originals.push(toInstant(series, f));
      if (originals.length > limit)
        throw new RecurrenceError(`More than ${limit} occurrences in range`);
    }
  }

  const result: Occurrence[] = [];
  const seen = new Set<number>();
  for (const originalStart of originals) {
    seen.add(originalStart.getTime());
    const ex = byOriginal.get(originalStart.getTime());
    if (ex?.cancelled) continue;
    const start = ex?.start ?? originalStart;
    const end = ex?.end ?? new Date(start.getTime() + duration);
    if (overlaps(start, end, range)) {
      result.push({ originalStart, start, end, modified: ex !== undefined });
    }
  }

  // Occurrences moved into the range from outside it.
  for (const ex of exceptions) {
    if (ex.cancelled || seen.has(ex.originalStart.getTime()) || !ex.start) continue;
    const end = ex.end ?? new Date(ex.start.getTime() + duration);
    if (overlaps(ex.start, end, range) && isOccurrence(series, ex.originalStart)) {
      result.push({ originalStart: ex.originalStart, start: ex.start, end, modified: true });
    }
  }

  return result.sort((a, b) => a.start.getTime() - b.start.getTime());
}

/** True when `originalStart` is generated by the series (used to validate exception targets). */
export function isOccurrence(series: SeriesDefinition, originalStart: Date): boolean {
  const rule = buildRule(series);
  if (!rule) return originalStart.getTime() === series.start.getTime();
  const f = series.allDay ? originalStart : instantToFloating(originalStart, series.timeZone);
  if (toInstant(series, f).getTime() !== originalStart.getTime()) return false;
  return rule.between(f, f, true).length > 0;
}

/** First occurrence start strictly after `after` (or inclusive), or null when the series ended. */
export function nextOccurrence(
  series: SeriesDefinition,
  after: Date,
  inclusive = false,
): Date | null {
  const rule = buildRule(series);
  if (!rule) {
    const ok = inclusive ? series.start >= after : series.start > after;
    return ok ? series.start : null;
  }
  const f = series.allDay ? after : instantToFloating(after, series.timeZone);
  let next = rule.after(f, inclusive);
  // Floating comparison can be off by the DST hour; step until the instant is really after.
  while (next) {
    const instant = toInstant(series, next);
    if (inclusive ? instant >= after : instant > after) return instant;
    next = rule.after(next, false);
  }
  return null;
}

function stringifyOptions(options: Partial<RRuleOptions>): string {
  // Drop DTSTART; we store it separately.
  return RRule.optionsToString({ ...options, dtstart: null })
    .split('\n')
    .filter((l) => l.startsWith('RRULE:'))
    .map((l) => l.slice('RRULE:'.length))
    .join('');
}

export interface SeriesSplit {
  /** Rule for the original series, now ending before `at`; null means "no occurrences remain". */
  headRrule: string | null;
  /** Rule for the new series starting at `at`. */
  tailRrule: string;
}

/**
 * Implements "edit this and following": the original series stops before `at`,
 * a new series with the same rule (and remaining COUNT) starts at `at`.
 */
export function splitSeries(series: SeriesDefinition, at: Date): SeriesSplit {
  if (!series.rrule) throw new RecurrenceError('Cannot split a non-recurring entry');
  if (!isOccurrence(series, at)) throw new RecurrenceError('Split point is not an occurrence');
  const options = parseRecurrenceRule(series.rrule);
  const rule = buildRule(series) as RRule;
  const atF = series.allDay ? at : instantToFloating(at, series.timeZone);
  const before = rule.between(floatingStart(series), new Date(atF.getTime() - 1000), true).length;
  const tail: Partial<RRuleOptions> = { ...options };
  if (options.count) tail.count = options.count - before;
  if (before === 0) return { headRrule: null, tailRrule: stringifyOptions(tail) };
  const head: Partial<RRuleOptions> = { ...options, count: null, until: null };
  if (options.count) head.count = before;
  else head.until = new Date(atF.getTime() - 1000);
  return {
    headRrule: stringifyOptions(head),
    tailRrule: stringifyOptions(tail),
  };
}

/**
 * End of the last occurrence for bounded series (COUNT/UNTIL), null for open-ended ones.
 * Stored as `series_end_at` so range queries can skip finished series.
 */
export function seriesEnd(series: SeriesDefinition, maxOccurrences = 10_000): Date | null {
  if (!series.rrule) return series.end;
  const options = parseRecurrenceRule(series.rrule);
  if (!options.count && !options.until) return null;
  const rule = buildRule(series) as RRule;
  const all = rule.all((_d, i) => i < maxOccurrences);
  const last = all[all.length - 1];
  return last ? new Date(toInstant(series, last).getTime() + durationMs(series)) : series.end;
}
