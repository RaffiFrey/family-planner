export function normalizeItem(text: string): string {
  return text.toLowerCase().normalize('NFC').replace(/\s+/g, ' ').trim();
}

/** Guesses the store section for an item text; `other` when unknown. */
export function guessCategory(text: string): ItemCategory {
  const t = ` ${normalizeItem(text)} `;
  for (const [category, words] of KEYWORDS) {
    if (words.some((w) => t.includes(w))) return category;
  }
  return 'other';
}
