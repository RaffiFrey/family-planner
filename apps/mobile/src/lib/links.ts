import type { Href } from 'expo-router';
import { APP_SCHEME } from './env';

/** Extracts an invite token from a pasted token, `familyplaner://join/<token>` or a web invite URL. */
export function parseInviteToken(input: string): string | null {
  const s = input.trim();
  if (s === '') return null;
  const m = /(?:join|invitations?|invite)\/([A-Za-z0-9_-]{16,})/.exec(s);
  if (m?.[1]) return m[1];
  return /^[A-Za-z0-9_-]{16,}$/.test(s) ? s : null;
}

export function inviteLink(token: string): string {
  return `${APP_SCHEME}://join/${token}`;
}

/**
 * Maps a notification `link` (web-style path such as `/tasks/<id>`) to an app route.
 * Unknown links open the notification inbox.
 */
export function notificationLinkToRoute(link: string | null | undefined): Href {
  // Typed routes (generated by `expo start`) narrow Href; the mapped paths are valid app routes.
  const path: unknown = linkPath(link);
  return path as Href;
}

function linkPath(link: string | null | undefined): string {
  if (!link) return '/notifications';
  const path = link.replace(/^[a-z]+:\/\/[^/]*/i, '').split(/[?#]/)[0] ?? '';
  const seg = path.split('/').filter(Boolean);
  const [first, second, third] = seg;
  switch (first) {
    case 'tasks':
      return second ? `/tasks/${second}` : '/tasks';
    case 'lists':
      return second ? `/lists/${second}` : '/lists';
    case 'events':
      return second ? `/events/${second}` : '/calendar';
    case 'calendar':
      return second === 'events' && third ? `/events/${third}` : '/calendar';
    case 'finance':
      return second === 'budgets'
        ? '/finance/budgets'
        : second === 'transactions'
          ? '/finance/transactions'
          : '/finance';
    case 'files':
    case 'storage':
      return '/files';
    case 'household':
    case 'family':
      return '/family';
    case 'notifications':
      return '/notifications';
    default:
      return '/notifications';
  }
}
